/** A card whose four buttons are the right answer plus three others from `pool`, with the right one at slot `k % 4`. */
function card(k: number, text: string, right: string, pool: string[], why: string, page: number, tag: string, icon: string): SortCard {
  const others = pool.filter((p) => p !== right);
  const pick = [0, 1, 2].map((j) => others[(k + j * 2) % others.length]);
  const uniq = [...new Set(pick)];
  for (const o of others) if (uniq.length < 3 && !uniq.includes(o)) uniq.push(o);
  const slot = k % 4;
  const buckets = [...uniq.slice(0, 3)];
  buckets.splice(slot, 0, right);
  return { text, bucket: slot, buckets, why, page, tag, icon };
}

